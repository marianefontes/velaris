function CodePanel({
  title,
  badge,
  iconLabel,
  iconTone,
  code,
}: ExampleBlock) {
  return (
    <article className="glass-panel rounded-2xl p-8">
      <div className="mb-5 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <div className={`flex h-8 w-8 items-center justify-center rounded-lg text-xs font-black ${iconTone}`}>
            {iconLabel}
          </div>
          <p className="text-sm font-black text-white">{title}</p>
        </div>
        <span className="rounded-lg border border-white/10 px-2 py-1 text-[10px] font-bold uppercase tracking-widest text-slate-500">
          {badge}
        </span>
      </div>
      <pre className="overflow-x-auto rounded-xl border border-white/10 bg-background/80 p-5 text-xs leading-relaxed text-slate-300">
        <code>{code}</code>
      </pre>
    </article>
  );
}

function methodTone(method: Endpoint["method"]) {
  if (method === "GET") return "bg-success/20 text-success";
  if (method === "POST") return "bg-sky-500/20 text-sky-400";
  return "bg-warning/20 text-warning";
}

