type CopyKey = keyof typeof copy;
export type ComponentsPreviewCopy = Record<CopyKey, string>;

const localeIndex: Record<Locale, 0 | 1 | 2> = {
  "pt-BR": 0,
  "pt-PT": 1,
  "en-US": 2,
};

export function getComponentsPreviewCopy(locale: Locale): ComponentsPreviewCopy {
  const index = localeIndex[locale];
  return Object.fromEntries(
    Object.entries(copy).map(([key, values]) => [key, values[index]]),
  ) as ComponentsPreviewCopy;
}
